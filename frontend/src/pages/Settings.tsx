import { useState } from "react";

function readName(): string {
  try {
    return localStorage.getItem("nextstep_display_name") ?? "";
  } catch {
    return "";
  }
}

export function Settings() {
  const [name, setName] = useState(readName);
  const [saved, setSaved] = useState(false);

  function handleSave() {
    try {
      localStorage.setItem("nextstep_display_name", name.trim());
      setSaved(true);
    } catch {
      setSaved(false);
    }
  }

  return (
    <div className="page page-narrow">
      <div className="page-head">
        <div>
          <h1>Settings</h1>
          <p className="lede">Preferences are stored only in this browser.</p>
        </div>
      </div>

      <form
        className="panel"
        onSubmit={(e) => {
          e.preventDefault();
          handleSave();
        }}
      >
        <div className="field">
          <label htmlFor="display-name">Display name</label>
          <input
            id="display-name"
            type="text"
            value={name}
            onChange={(e) => {
              setName(e.target.value);
              setSaved(false);
            }}
            maxLength={60}
          />
        </div>
        <div className="actions" style={{ alignItems: "center" }}>
          <button type="submit" className="btn btn-ink">
            Save
          </button>
          {saved && (
            <span className="muted" role="status">
              Saved
            </span>
          )}
        </div>
      </form>

      <section className="panel">
        <h2 className="section-title">About NextStep AI</h2>
        <p className="muted">
          Plans are generated by an AI model running on the server. Its suggestions can be wrong; for health, legal or
          financial decisions, check with a qualified professional.
        </p>
      </section>
    </div>
  );
}
